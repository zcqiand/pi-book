pi -c                     # 续接当前目录最近的会话：同一份记录接着追加
pi --session <id或路径>    # 点名续接：id 支持只写前缀
pi -r                     # 弹出会话选择器，挑一个续接
pi -n <名字>               # 给会话起个显示名，选择器里好认
pi --export <文件>         # 把会话导出成 HTML 归档后退出
pi --session-dir <目录>    # 会话的存取目录覆盖
pi --no-session           # 本次不存会话：临时任务，不留痕